use anyhow::Context;
use std::collections::BTreeMap;
use std::path::Path;

pub struct ServerProperties {
    properties: BTreeMap<String, String>,
}

impl ServerProperties {
    pub fn load_or_default(path: &Path) -> Self {
        let mut props = BTreeMap::new();
        if path.exists() {
            if let Ok(content) = std::fs::read_to_string(path) {
                for line in content.lines() {
                    let trimmed = line.trim();
                    if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with('!') {
                        continue;
                    }
                    if let Some((k, v)) = trimmed.split_once('=') {
                        props.insert(k.trim().to_string(), v.trim().to_string());
                    }
                }
            }
        }
        Self { properties: props }
    }

    #[allow(dead_code)]
    pub fn get(&self, key: &str) -> Option<&str> {
        self.properties.get(key).map(|s| s.as_str())
    }

    pub fn set(&mut self, key: &str, value: &str) {
        self.properties.insert(key.to_string(), value.to_string());
    }

    pub fn save(&self, path: &Path) -> anyhow::Result<()> {
        let mut out = String::from("# Minecraft server properties (Generated by mcserman)\n");
        for (k, v) in &self.properties {
            out.push_str(&format!("{}={}\n", k, v));
        }
        std::fs::write(path, out).with_context(|| {
            format!(
                "No se pudo escribir server.properties en {}",
                path.display()
            )
        })?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_server_properties_crud() {
        let mut props =
            ServerProperties::load_or_default(Path::new("/nonexistent/server.properties"));
        props.set("server-port", "25565");
        props.set("motd", "Servidor Test");

        assert_eq!(props.get("server-port"), Some("25565"));
        assert_eq!(props.get("motd"), Some("Servidor Test"));
        assert_eq!(props.get("difficulty"), None);
    }
}
